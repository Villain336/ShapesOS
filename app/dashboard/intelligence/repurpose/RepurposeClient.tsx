// Marketr — Phase 12: Repurpose client.
// Format sub-tabs (icon + label, active = border-ink text-ink),
// topic input, generate, cited results with an honest mock banner.

"use client";

import { useState } from "react";
import {
  FileText,
  Clapperboard,
  MessagesSquare,
  Mail,
  Loader2,
  Copy,
  Check,
  AlertTriangle,
  BookOpen,
} from "lucide-react";
import type { RepurposeFormat, RepurposeResult } from "@/lib/content/repurpose";

const FORMAT_ICONS: Record<string, typeof FileText> = {
  brief: FileText,
  "video-script": Clapperboard,
  "social-thread": MessagesSquare,
  newsletter: Mail,
};

export function RepurposeClient({ formats }: { formats: RepurposeFormat[] }) {
  const [formatId, setFormatId] = useState(formats[0]?.id ?? "brief");
  const [topic, setTopic] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<RepurposeResult | null>(null);
  const [copied, setCopied] = useState(false);

  async function run() {
    if (!topic.trim() || loading) return;
    setLoading(true);
    setError(null);
    setResult(null);
    try {
      const res = await fetch("/api/content/repurpose", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ topic: topic.trim(), format: formatId }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? "Repurpose failed");
      setResult(data as RepurposeResult);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Repurpose failed");
    } finally {
      setLoading(false);
    }
  }

  async function copyAsset() {
    if (!result) return;
    await navigator.clipboard.writeText(result.asset);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  }

  const activeFormat = formats.find((f) => f.id === formatId);

  return (
    <div className="flex flex-col gap-4">
      {/* Format sub-tabs */}
      <div className="flex flex-wrap gap-1 border-b border-line">
        {formats.map((f) => {
          const Icon = FORMAT_ICONS[f.id] ?? FileText;
          const active = f.id === formatId;
          return (
            <button
              key={f.id}
              onClick={() => setFormatId(f.id)}
              className={`flex items-center gap-1.5 border-b-2 px-3 py-2 text-[13px] font-medium transition-colors ${
                active
                  ? "border-ink text-ink"
                  : "border-transparent text-muted hover:text-ink"
              }`}
            >
              <Icon className="h-3.5 w-3.5" />
              {f.label}
            </button>
          );
        })}
      </div>

      {/* Topic input */}
      <div className="rounded-lg border border-line bg-white p-4">
        <p className="text-[13px] text-muted">{activeFormat?.description}</p>
        <div className="mt-3 flex gap-2">
          <input
            value={topic}
            onChange={(e) => setTopic(e.target.value)}
            onKeyDown={(e) => e.key === "Enter" && run()}
            placeholder="e.g. positioning for early-stage SaaS"
            className="flex-1 rounded-md border border-line bg-canvas px-3 py-2 text-sm text-ink placeholder:text-subtle focus:border-ink focus:outline-none"
          />
          <button
            onClick={run}
            disabled={loading || !topic.trim()}
            className="flex items-center gap-1.5 rounded-md bg-ink px-4 py-2 text-sm font-medium text-white hover:bg-night-hover disabled:opacity-50"
          >
            {loading && <Loader2 className="h-4 w-4 aos-spin" />}
            {loading ? "Repurposing…" : "Generate"}
          </button>
        </div>
        {error && (
          <p className="mt-2 flex items-center gap-1.5 text-[13px] text-failed-text">
            <AlertTriangle className="h-3.5 w-3.5" /> {error}
          </p>
        )}
      </div>

      {/* Result */}
      {result && (
        <div className="rounded-lg border border-line bg-white p-4">
          {result.mock && (
            <div className="mb-3 flex items-center gap-1.5 rounded-md border border-line bg-canvas px-3 py-2 text-[13px] text-muted">
              <AlertTriangle className="h-3.5 w-3.5" />
              No LLM key configured — this draft was generated by the mock provider. Add a key
              under Settings → Providers for live expert synthesis.
            </div>
          )}
          <div className="flex items-start justify-between gap-3">
            <h2 className="text-sm font-semibold text-ink">
              {activeFormat?.label} · {result.topic}
            </h2>
            <button
              onClick={copyAsset}
              className="flex shrink-0 items-center gap-1 rounded-md border border-line px-2 py-1 text-[12px] font-medium text-muted hover:bg-hover-paper"
            >
              {copied ? <Check className="h-3.5 w-3.5" /> : <Copy className="h-3.5 w-3.5" />}
              {copied ? "Copied" : "Copy"}
            </button>
          </div>
          <pre className="mt-2 max-h-[480px] overflow-auto whitespace-pre-wrap rounded-md bg-canvas p-3 text-[13px] leading-relaxed text-ink">
            {result.asset}
          </pre>
          {result.sources.length > 0 && (
            <div className="mt-3 border-t border-line pt-2">
              <p className="flex items-center gap-1 text-[12px] font-medium text-muted">
                <BookOpen className="h-3.5 w-3.5" /> Sources
              </p>
              <ul className="mt-1 space-y-0.5">
                {result.sources.map((s, i) => (
                  <li key={i} className="text-[12px] text-muted">
                    {s.title} — {s.author} <span className="text-subtle">({s.license})</span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
