import configPromise from "@payload-config";
import "@payloadcms/next/css";
import { handleServerFunctions, RootLayout } from "@payloadcms/next/layouts";
import type { ServerFunctionClient } from "payload";
import React from "react";

import { importMap } from "./admin/importMap.js";

/**
 * Adapts Payload's full server-function handler (needs config + importMap)
 * to the client-callable ServerFunctionClient shape RootLayout expects.
 * Declared as a Server Action so the admin client can invoke it.
 */
const serverFunction: ServerFunctionClient = async (args) => {
  "use server";
  return handleServerFunctions({ ...args, config: configPromise, importMap });
};

/**
 * Payload CMS shell (Phase 12) — mounted at /admin.
 *
 * RootLayout renders Payload's providers plus its own <html>/<body>
 * (Payload's documented integration pattern for an existing Next.js app;
 * the HTML parser merges the inner html/body attributes — incl. data-theme —
 * onto the document elements, so theming keeps working).
 *
 * Lazy-load note: Next code-splits per route segment, so the entire Payload
 * admin (incl. @payloadcms/ui) ships ONLY in the /admin chunk — the main
 * Marketr bundle is untouched. The import map is generated by
 * `npx tsx scripts/payload-importmap.mts` into ./admin/importMap.js.
 */
export default async function PayloadShellLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <RootLayout
      config={configPromise}
      importMap={importMap}
      serverFunction={serverFunction}
    >
      {children}
    </RootLayout>
  );
}
