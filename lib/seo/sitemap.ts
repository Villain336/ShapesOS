// ShapesOS Phase 11 (seotools): sitemaps for SiteBuilder / IDE sites.
//
// Pure helpers (the XML renderer is shared with the programmatic-SEO
// sitemap, lib/seo/programmatic-service.ts buildSitemapXml):
//   renderSitemapXml(entries)          <urlset> with escaped <loc>s
//   sitemapEntriesForFiles(files, o)   the indexable HTML pages of a working
//                                      copy as absolute URLs (noindex, error
//                                      pages and pages canonicalised elsewhere
//                                      left out)
//   robotsWithSitemap(robots, url)     robots.txt with our Sitemap: line
//   indexNowKey(siteId, secret)        the site's IndexNow key (derived, so
//                                      nothing new is stored)
//
// refreshSiteSitemap() writes sitemap.xml, the robots.txt Sitemap line and
// the IndexNow key file into the site's working copy. It runs when a person
// applies a draft (lib/sites/apply.ts) and right before a hosting deploy
// (app/api/websites/[id]/deploy-hosting), so what goes live carries a fresh
// sitemap. A sitemap.xml the site owner wrote by hand (no ShapesOS marker)
// is never overwritten.

import { createHmac } from "node:crypto";
import { prisma } from "@/lib/prisma";
import type { LocalDirProvider } from "@/lib/connectors/local";
import { readSiteWorkingCopy, workingCopy, type SiteFile } from "@/lib/sites/files";
import { resolveLiveAuditUrl } from "@/lib/audit/project-audit";
import { urlPathForFile } from "./jsonld";

export const SHAPES_SITEMAP_MARKER = "<!-- Generated by ShapesOS: rebuilt on every publish. Remove this line to manage the sitemap by hand. -->";

export interface SitemapEntry {
  loc: string;
  lastmod?: string;
}

function xmlEscape(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

/** A sitemaps.org <urlset> document. `marker` adds the ShapesOS ownership comment. */
export function renderSitemapXml(entries: SitemapEntry[], opts: { marker?: boolean } = {}): string {
  const urls = entries
    .map((e) => `  <url>\n    <loc>${xmlEscape(e.loc)}</loc>${e.lastmod ? `\n    <lastmod>${xmlEscape(e.lastmod)}</lastmod>` : ""}\n  </url>`)
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n${opts.marker ? `${SHAPES_SITEMAP_MARKER}\n` : ""}<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

const ERROR_PAGE = /(^|\/)(404|500|50x|error|not-found)\.html?$/i;

function isNoindex(html: string): boolean {
  for (const m of html.matchAll(/<meta\b[^>]*>/gi)) {
    const tag = m[0];
    if (/name\s*=\s*["']?(robots|googlebot)["']?/i.test(tag) && /content\s*=\s*["'][^"']*\b(noindex|none)\b/i.test(tag)) return true;
  }
  return false;
}

function canonicalOf(html: string): string | null {
  for (const m of html.matchAll(/<link\b[^>]*>/gi)) {
    if (/rel\s*=\s*["']?[^"'>]*\bcanonical\b/i.test(m[0])) {
      return /href\s*=\s*["']([^"']+)["']/i.exec(m[0])?.[1] ?? null;
    }
  }
  return null;
}

/** The indexable pages of a working copy, as absolute URLs on `origin`. PURE. */
export function sitemapEntriesForFiles(files: readonly SiteFile[], origin: string): SitemapEntry[] {
  const base = origin.replace(/\/+$/, "");
  const out = new Map<string, SitemapEntry>();
  for (const f of files) {
    if (!/\.html?$/i.test(f.path) || ERROR_PAGE.test(f.path)) continue;
    if (isNoindex(f.content)) continue;
    const loc = `${base}${urlPathForFile(f.path)}`;
    const canonical = canonicalOf(f.content);
    if (canonical) {
      let abs: string;
      try {
        abs = new URL(canonical, `${base}/`).toString();
      } catch {
        abs = loc;
      }
      // Canonicalised to another URL: that URL is the one to list (when it's ours).
      if (abs.replace(/\/$/, "") !== loc.replace(/\/$/, "")) {
        if (new URL(abs).origin === new URL(base).origin) out.set(abs, { loc: abs });
        continue;
      }
    }
    out.set(loc, { loc });
  }
  return [...out.values()].sort((a, b) => a.loc.localeCompare(b.loc));
}

/** robots.txt that names `sitemapUrl` (created when missing; existing rules kept). PURE. */
export function robotsWithSitemap(existing: string | null, sitemapUrl: string): string {
  if (existing === null || !existing.trim()) return `User-agent: *\nAllow: /\n\nSitemap: ${sitemapUrl}\n`;
  const has = existing.split(/\r?\n/).some((l) => {
    const m = /^\s*sitemap\s*:\s*(\S+)/i.exec(l);
    return m && m[1] === sitemapUrl;
  });
  if (has) return existing;
  return `${existing.replace(/\s*$/, "")}\n\nSitemap: ${sitemapUrl}\n`;
}

/** The site's IndexNow key: 32 hex chars derived from the server secret and site id. */
export function indexNowKey(siteId: string, secret: string): string {
  return createHmac("sha256", secret).update(`indexnow:${siteId}`).digest("hex").slice(0, 32);
}

/** The secret IndexNow keys derive from (the credentials key; never sent anywhere). */
export function indexNowSecret(env: NodeJS.ProcessEnv = process.env): string | null {
  const s = (env.MARKETR_CREDENTIALS_KEY ?? env.NEXTAUTH_SECRET ?? env.AUTH_SECRET ?? "").trim();
  return s || null;
}

export interface SitemapRefresh {
  /** Null when the site has no live URL yet (no deployment, no project domain). */
  sitemapUrl: string | null;
  urlCount: number;
  written: string[];
  /** Why nothing (or not everything) was written. */
  skipped: "no_origin" | "user_managed" | null;
  indexNowKey: string | null;
}

/**
 * Write sitemap.xml + the robots.txt Sitemap line + the IndexNow key file
 * into the site's working copy (only files whose content changes). Never
 * throws for "nothing to do"; I/O errors propagate.
 */
export async function refreshSiteSitemap(input: {
  siteId: string;
  projectId: string;
  origin?: string | null;
  provider?: LocalDirProvider;
  secret?: string | null;
}): Promise<SitemapRefresh> {
  const provider = input.provider ?? workingCopy(input.siteId);
  const live = input.origin ?? (await resolveLiveAuditUrl(input.siteId, input.projectId));
  let origin: string | null = null;
  try {
    origin = live ? new URL(live).origin : null;
  } catch {
    origin = null;
  }
  if (!origin) return { sitemapUrl: null, urlCount: 0, written: [], skipped: "no_origin", indexNowKey: null };

  const { files } = await readSiteWorkingCopy(input.siteId, provider);
  const byPath = new Map(files.map((f) => [f.path, f.content]));
  const sitemapUrl = `${origin}/sitemap.xml`;
  const entries = sitemapEntriesForFiles(files, origin);
  const written: string[] = [];
  let skipped: SitemapRefresh["skipped"] = null;

  const writeIfChanged = async (path: string, content: string) => {
    if (byPath.get(path) === content) return;
    await provider.writeFile(path, content);
    written.push(path);
  };

  const current = byPath.get("/sitemap.xml");
  if (current !== undefined && !current.includes(SHAPES_SITEMAP_MARKER)) {
    skipped = "user_managed";
  } else {
    await writeIfChanged("/sitemap.xml", renderSitemapXml(entries, { marker: true }));
  }
  await writeIfChanged("/robots.txt", robotsWithSitemap(byPath.get("/robots.txt") ?? null, sitemapUrl));

  const secret = input.secret === undefined ? indexNowSecret() : input.secret;
  const key = secret ? indexNowKey(input.siteId, secret) : null;
  if (key) await writeIfChanged(`/${key}.txt`, key);

  if (written.length) {
    await prisma.fileChangeLog
      .create({
        data: {
          projectId: input.projectId,
          siteId: input.siteId,
          filePath: "/sitemap.xml",
          actor: "system",
          action: "save",
          summary: `Rebuilt ${written.join(", ")} (${entries.length} page${entries.length === 1 ? "" : "s"} in the sitemap)`,
        },
      })
      .catch(() => undefined);
  }
  return { sitemapUrl, urlCount: entries.length, written, skipped, indexNowKey: key };
}
