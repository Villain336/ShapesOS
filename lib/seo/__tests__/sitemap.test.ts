import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { indexNowKey, renderSitemapXml, robotsWithSitemap, SHAPES_SITEMAP_MARKER, sitemapEntriesForFiles } from "../sitemap";
import { INDEXNOW_ENDPOINT, submitToIndexNow, submitToSearchConsole } from "../sitemap-submit";

const publicDns = async () => ["93.184.216.34"];

describe("renderSitemapXml", () => {
  it("renders a urlset with escaped locs, optional lastmod and marker", () => {
    const xml = renderSitemapXml([{ loc: "https://a.example/?a=1&b=<2>", lastmod: "2026-10-01" }, { loc: "https://a.example/x" }], { marker: true });
    assert.match(xml, /^<\?xml version="1.0" encoding="UTF-8"\?>\n<!-- Generated by ShapesOS/);
    assert.match(xml, /<loc>https:\/\/a.example\/\?a=1&amp;b=&lt;2&gt;<\/loc>\n {4}<lastmod>2026-10-01<\/lastmod>/);
    assert.match(xml, /<url>\n {4}<loc>https:\/\/a.example\/x<\/loc>\n {2}<\/url>/);
    assert.doesNotMatch(renderSitemapXml([]), /ShapesOS/);
  });
});

describe("sitemapEntriesForFiles", () => {
  it("lists indexable pages as absolute URLs", () => {
    const entries = sitemapEntriesForFiles(
      [
        { path: "/index.html", content: "<h1>home</h1>" },
        { path: "/about.html", content: "<h1>about</h1>" },
        { path: "/blog/index.html", content: "" },
        { path: "/404.html", content: "not found" },
        { path: "/private.html", content: '<meta name="robots" content="noindex, nofollow">' },
        { path: "/old.html", content: '<link rel="canonical" href="/about">' },
        { path: "/syndicated.html", content: '<link rel="canonical" href="https://other.example/post">' },
        { path: "/self.html", content: '<link rel="canonical" href="https://acme.example/self">' },
        { path: "/style.css", content: "" },
      ],
      "https://acme.example/",
    );
    assert.deepEqual(entries.map((e) => e.loc), [
      "https://acme.example/",
      "https://acme.example/about",
      "https://acme.example/blog/",
      "https://acme.example/self",
    ]);
  });
});

describe("robotsWithSitemap", () => {
  const url = "https://acme.example/sitemap.xml";
  it("creates, appends and leaves alone", () => {
    assert.equal(robotsWithSitemap(null, url), `User-agent: *\nAllow: /\n\nSitemap: ${url}\n`);
    assert.equal(robotsWithSitemap("User-agent: *\nDisallow: /admin\n\n", url), `User-agent: *\nDisallow: /admin\n\nSitemap: ${url}\n`);
    const has = `User-agent: *\nsitemap: ${url}\n`;
    assert.equal(robotsWithSitemap(has, url), has);
  });
});

describe("indexNowKey", () => {
  it("is 32 hex chars, stable per site and secret", () => {
    const k = indexNowKey("site-1", "secret");
    assert.match(k, /^[0-9a-f]{32}$/);
    assert.equal(indexNowKey("site-1", "secret"), k);
    assert.notEqual(indexNowKey("site-2", "secret"), k);
    assert.notEqual(indexNowKey("site-1", "other"), k);
  });
  it("marker text is stable (hand-written sitemaps are detected by it)", () => {
    assert.match(SHAPES_SITEMAP_MARKER, /Generated by ShapesOS/);
  });
});

function stub(status: number, body = "") {
  const calls: { url: string; init: RequestInit }[] = [];
  const fn = (async (url: string, init: RequestInit) => {
    calls.push({ url, init });
    return new Response(body, { status });
  }) as unknown as typeof fetch;
  return { fn, calls };
}

describe("submitToIndexNow (stubbed — labelled mock)", () => {
  const input = { host: "acme.example", key: "k".repeat(32), keyLocation: "https://acme.example/kkkk.txt", urls: ["https://acme.example/", "https://acme.example/about"] };

  it("posts host, key, keyLocation and the URL list", async () => {
    const { fn, calls } = stub(200);
    const r = await submitToIndexNow(input, { fetchImpl: fn, resolve: publicDns });
    assert.deepEqual(r, { target: "indexnow", status: "submitted", httpStatus: 200, detail: "IndexNow accepted 2 URLs." });
    assert.equal(calls[0].url, INDEXNOW_ENDPOINT);
    assert.equal(calls[0].init.method, "POST");
    assert.deepEqual(JSON.parse(String(calls[0].init.body)), { host: "acme.example", key: input.key, keyLocation: input.keyLocation, urlList: input.urls });
  });

  it("reports 202 as pending validation and errors truthfully", async () => {
    assert.match((await submitToIndexNow(input, { fetchImpl: stub(202).fn, resolve: publicDns })).detail, /validation pending/);
    for (const [status, re] of [[403, /publish the site/], [422, /don't belong/], [429, /rate-limiting/], [500, /HTTP 500/]] as const) {
      const r = await submitToIndexNow(input, { fetchImpl: stub(status).fn, resolve: publicDns });
      assert.equal(r.status, "failed");
      assert.match(r.detail, re);
    }
    const down = (async () => {
      throw new Error("ECONNRESET");
    }) as unknown as typeof fetch;
    assert.match((await submitToIndexNow(input, { fetchImpl: down, resolve: publicDns })).detail, /could not be reached/);
    assert.equal((await submitToIndexNow({ ...input, urls: [] }, { fetchImpl: stub(200).fn })).status, "failed");
  });
});

describe("submitToSearchConsole (stubbed — labelled mock)", () => {
  const args = { workspaceId: "w", projectId: "p", sitemapUrl: "https://acme.example/sitemap.xml" };
  const token = async () => ({ accessToken: "tok", property: "sc-domain:acme.example" });

  it("PUTs the sitemap to the property", async () => {
    const { fn, calls } = stub(200);
    const r = await submitToSearchConsole(args, { getToken: token, fetchImpl: fn, resolve: publicDns });
    assert.equal(r.status, "submitted");
    assert.equal(calls[0].init.method, "PUT");
    assert.equal(
      calls[0].url,
      "https://www.googleapis.com/webmasters/v3/sites/sc-domain%3Aacme.example/sitemaps/https%3A%2F%2Facme.example%2Fsitemap.xml",
    );
    assert.equal(new Headers(calls[0].init.headers).get("authorization"), "Bearer tok");
  });

  it("not connected, read-only grants and errors are never 'submitted'", async () => {
    const none = await submitToSearchConsole(args, {
      getToken: async () => {
        throw new Error('GSC not connected for project p: bind the "google-search-console" connector first');
      },
    });
    assert.equal(none.status, "not_connected");
    const expired = await submitToSearchConsole(args, {
      getToken: async () => {
        throw new Error("GSC token for project p expired and refresh failed — reconnect the connector");
      },
    });
    assert.equal(expired.status, "needs_reconnect");
    const readOnly = await submitToSearchConsole(args, {
      getToken: token,
      fetchImpl: stub(403, JSON.stringify({ error: { message: "Request had insufficient authentication scopes." } })).fn,
      resolve: publicDns,
    });
    assert.equal(readOnly.status, "needs_reconnect");
    const broken = await submitToSearchConsole(args, { getToken: token, fetchImpl: stub(500).fn, resolve: publicDns, maxRetries: 0 });
    assert.equal(broken.status, "failed");
    assert.equal(broken.httpStatus, 500);
  });
});
