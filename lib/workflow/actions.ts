// Marketr — automation canvas: action implementations (redesign §2).
//
// Every action reuses an existing server capability (content engine,
// audit runner, internal-link sync, alert hub, report generator,
// autopilot publish). Nothing is reimplemented here — this file only
// adapts node config → service call and returns a JSON-serializable
// output that later nodes (conditions) can read from run context.

import { prisma } from "@/lib/prisma";
import { defaultDraftGenerator } from "@/lib/seo/autopilot-service";
import { publishAutopilotItem } from "@/lib/seo/autopilot-service";
import { runAudit } from "@/lib/audit/audit";
import { refreshInternalLinkSuggestions } from "@/lib/seo/internal-links-sync";
import { emitAlert } from "@/lib/alerts/evaluate";
import { generateReport } from "@/lib/pdf/generate";
import { wordCount } from "@/lib/content/brief";
import {
  createWorkflowAutopilotItem,
  ensureWorkflowDraftsRule,
} from "./approvals";

export interface ActionExecContext {
  workspaceId: string;
  projectId: string;
  runId: string;
  nodeId: string;
  /** User id, or "cron"/"system" for non-interactive runs. */
  actor: string;
  /** Accumulated outputs of earlier nodes in this run. */
  context: Record<string, unknown>;
}

function str(v: unknown): string {
  return typeof v === "string" ? v.trim() : "";
}

type Output = Record<string, unknown>;

async function generateDraft(config: Record<string, unknown>, ctx: ActionExecContext): Promise<Output> {
  const topic = str(config.topic) || str(config.brief);
  if (!topic) throw new Error("generate_draft: config.topic is required");
  const sourceRef = `workflow_run:${ctx.runId}:${ctx.nodeId}`;
  const draft = await defaultDraftGenerator({
    kind: "keyword_brief",
    sourceRef,
    title: topic,
    brief: str(config.brief) || topic,
    priority: 0,
  });
  const rule = await ensureWorkflowDraftsRule(prisma, ctx.workspaceId, ctx.projectId);
  const item = await createWorkflowAutopilotItem(prisma, rule, {
    projectId: ctx.projectId,
    kind: "keyword_brief",
    sourceRef,
    title: draft.title,
    summary: `Draft generated by workflow run ${ctx.runId}. Review in the approval queue.`,
    draftMarkdown: draft.markdown,
  });
  return { itemId: item.id, title: draft.title, wordCount: wordCount(draft.markdown) };
}

async function runSeoAudit(config: Record<string, unknown>, ctx: ActionExecContext): Promise<Output> {
  let siteId = str(config.siteId);
  let siteName = "site";
  if (!siteId) {
    const site = await prisma.site.findFirst({
      where: { projectId: ctx.projectId },
      orderBy: { createdAt: "asc" },
      select: { id: true, name: true },
    });
    if (!site) {
      throw new Error("run_audit: this project has no site — add one or set siteId in the node config");
    }
    siteId = site.id;
    siteName = site.name;
  }
  // provider: null → mock findings (no live connector required for v1).
  const res = await runAudit({ siteId, projectId: ctx.projectId, siteName, provider: null, mock: false });
  return {
    auditId: res.audit.id,
    totalIssues: res.audit.totalIssues ?? 0,
    errorIssues: res.audit.errorIssues ?? 0,
    openIssues: res.audit.openIssues ?? 0,
  };
}

async function applyInternalLinks(_config: Record<string, unknown>, ctx: ActionExecContext): Promise<Output> {
  const res = await refreshInternalLinkSuggestions(ctx.projectId, ctx.workspaceId);
  return { created: res.created, updated: res.updated, skippedExisting: res.skippedExisting };
}

async function sendAlert(config: Record<string, unknown>, ctx: ActionExecContext): Promise<Output> {
  const title = str(config.title);
  if (!title) throw new Error("send_alert: config.title is required");
  const rawSeverity = str(config.severity);
  const severity = (["info", "warn", "critical"] as const).includes(rawSeverity as never)
    ? (rawSeverity as "info" | "warn" | "critical")
    : "info";
  const outcomes = await emitAlert({
    workspaceId: ctx.workspaceId,
    projectId: ctx.projectId,
    trigger: str(config.trigger) || "workflow",
    severity,
    title,
    body: str(config.body) || `Alert from workflow run ${ctx.runId}.`,
    dedupKey: `workflow:${ctx.runId}:${ctx.nodeId}`,
  });
  return {
    title,
    severity,
    rules: outcomes.map((o) => ({ ruleId: o.ruleId, ruleName: o.ruleName, status: o.status })),
  };
}

async function generateReportAction(config: Record<string, unknown>, ctx: ActionExecContext): Promise<Output> {
  const templateId = str(config.templateId);
  if (!templateId) throw new Error("generate_report: config.templateId is required");
  const template = await prisma.reportTemplate.findFirst({
    where: { id: templateId, workspaceId: ctx.workspaceId },
    select: { id: true, name: true },
  });
  if (!template) throw new Error("generate_report: report template not found in this workspace");
  const report = await generateReport({ templateId, actor: "system", actorId: ctx.actor });
  return { reportId: report.id, templateName: template.name };
}

async function publishApproved(config: Record<string, unknown>, ctx: ActionExecContext): Promise<Output> {
  const itemId = str(config.itemId) || str(ctx.context.approvedItemId);
  if (!itemId) {
    throw new Error(
      "publish_approved: no approved item — place this after an approval gate whose item was approved, or set itemId in the node config",
    );
  }
  // Fail-closed: publishAutopilotItem throws unless the item is approved
  // (and respects the kill switch internally).
  const res = await publishAutopilotItem(prisma, {
    workspaceId: ctx.workspaceId,
    projectId: ctx.projectId,
    itemId,
    actor: ctx.actor,
    userId: ctx.actor,
  });
  return { itemId, publishedUrl: res.publishedUrl };
}

/** Dispatch a single action node. Throws on any failure (fail-closed). */
export async function runActionNode(
  type: string,
  config: Record<string, unknown>,
  ctx: ActionExecContext,
): Promise<Output> {
  switch (type) {
    case "generate_draft":
      return generateDraft(config, ctx);
    case "run_audit":
      return runSeoAudit(config, ctx);
    case "apply_internal_links":
      return applyInternalLinks(config, ctx);
    case "send_alert":
      return sendAlert(config, ctx);
    case "generate_report":
      return generateReportAction(config, ctx);
    case "publish_approved":
      return publishApproved(config, ctx);
    default:
      throw new Error(`Unknown action type "${type}"`);
  }
}

/** JSON-safe deep merge helper for run context. */
export function mergeContext(base: Record<string, unknown>, patch: Record<string, unknown>) {
  return { ...base, ...patch };
}
