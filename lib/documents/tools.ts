// ShapesOS Phase 11 (seotools): document output tools (group "content").
//
//   create_document     spend  draft_document     .docx from markdown-ish text
//                                                 or blocks (lib/documents/docx)
//   create_spreadsheet  spend  draft_spreadsheet  .xlsx from rows / sheets or
//                                                 CSV (lib/documents/xlsx)
//
// Both save a WorkspaceFile through the workspace filesystem service (upload
// safety sniff, quota, storage) under /files/documents/<project>/<month>/ —
// the same store generated images use; nothing is sent anywhere. Tier 0
// drafts: they ask until a per-agent rule switches them to auto.
// Self-registers (imported for its side effect by lib/chat/agent.ts).

import { randomUUID } from "node:crypto";
import { registerExtraTool, type ToolDef } from "@/lib/chat/tools";
import { roleAtLeast } from "@/lib/authz";
import { writeFile, FsError } from "@/lib/filesystem/service";
import { workspaceFileUrl } from "@/lib/images/files";
import { parseCsv } from "@/lib/seo/programmatic";
import { coerceDocBlocks, markdownToDocBlocks, type DocBlock } from "./blocks";
import { buildDocx, DOCX_MIME } from "./docx";
import { buildXlsx, XLSX_MIME, type CellValue, type SheetInput } from "./xlsx";

export const DOCUMENT_FILES_ROOT = "/files/documents";

function str(v: unknown): string | undefined {
  return typeof v === "string" && v.trim() ? v.trim() : undefined;
}

function safeSegment(v: string): string {
  return v.replace(/[^A-Za-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "document";
}

/** Save generated bytes as a WorkspaceFile in the project's documents folder. */
export async function storeDocumentFile(opts: {
  workspaceId: string;
  projectId: string;
  userId: string;
  bytes: Buffer;
  title: string;
  ext: "docx" | "xlsx";
  mimeType: string;
  now?: Date;
}) {
  const month = (opts.now ?? new Date()).toISOString().slice(0, 7);
  const logicalPath = `${DOCUMENT_FILES_ROOT}/${safeSegment(opts.projectId)}/${month}/${safeSegment(opts.title.toLowerCase())}-${randomUUID().slice(0, 8)}.${opts.ext}`;
  const file = await writeFile({
    workspaceId: opts.workspaceId,
    logicalPath,
    kind: "file",
    bytes: opts.bytes,
    mimeType: opts.mimeType,
    createdBy: opts.userId,
  });
  return { file, url: workspaceFileUrl(opts.workspaceId, file.id) };
}

/** "1,234.5" stays text; "42", "-3.5", "1e3" become numbers; "007" (leading zero) stays text. */
export function inferCell(v: string): CellValue {
  const t = v.trim();
  if (t === "") return null;
  if (/^-?(0|[1-9]\d*)(\.\d+)?([eE][+-]?\d+)?$/.test(t) && t.length <= 15) return Number(t);
  if (/^(true|false)$/i.test(t)) return t.toLowerCase() === "true";
  return v;
}

/** Parse the agent's sheets / rows / csv arguments into sheets. */
export function parseSheetArgs(args: { sheets?: unknown; rows?: unknown; csv?: unknown; sheetName?: unknown }): SheetInput[] {
  const toRows = (rows: unknown, where: string): CellValue[][] => {
    if (!Array.isArray(rows)) throw new Error(`${where} must be an array of rows (arrays of cells).`);
    return rows.map((r, i) => {
      if (Array.isArray(r)) {
        return r.map((c) => (c === null || c === undefined ? null : typeof c === "number" || typeof c === "boolean" ? c : typeof c === "string" ? c : JSON.stringify(c)));
      }
      if (r && typeof r === "object") throw new Error(`${where}[${i}] is an object — pass rows as arrays, with the header as the first row.`);
      return [r as CellValue];
    });
  };
  const parse = (v: unknown) => (typeof v === "string" ? JSON.parse(v) : v);
  if (args.sheets !== undefined && args.sheets !== "") {
    let sheets: unknown;
    try {
      sheets = parse(args.sheets);
    } catch {
      throw new Error('sheets must be JSON: [{"name": "Sheet1", "rows": [["Header", …], [1, …]]}]');
    }
    if (!Array.isArray(sheets) || !sheets.length) throw new Error("sheets must be a non-empty array.");
    return sheets.map((s, i) => {
      const o = (s ?? {}) as { name?: unknown; rows?: unknown; header?: unknown };
      return { name: typeof o.name === "string" && o.name.trim() ? o.name : `Sheet${i + 1}`, rows: toRows(o.rows, `sheets[${i}].rows`), header: o.header !== false };
    });
  }
  const name = str(args.sheetName) ?? "Sheet1";
  if (args.rows !== undefined && args.rows !== "") {
    let rows: unknown;
    try {
      rows = parse(args.rows);
    } catch {
      throw new Error('rows must be JSON: [["Header", …], [1, …]]');
    }
    return [{ name, rows: toRows(rows, "rows"), header: true }];
  }
  const csv = str(args.csv);
  if (csv) {
    const parsed = parseCsv(csv);
    if (!parsed.columns.length) throw new Error("The CSV has no rows.");
    return [{ name, rows: [parsed.columns, ...parsed.rows.map((r) => parsed.columns.map((c) => inferCell(r[c] ?? "")))], header: true }];
  }
  throw new Error("Pass sheets, rows or csv.");
}

function fsFailure(err: unknown) {
  if (err instanceof FsError) return { summary: `Couldn't save the file: ${err.message}`, details: { error: err.code } };
  throw err;
}

export const create_document: ToolDef = {
  name: "create_document",
  description:
    "Create a Word document (.docx) and save it to the workspace files. Write the content as markdown (# headings, paragraphs, - bullets, 1. numbered, > quotes, ``` code, | tables |, --- dividers, **bold**, *italic*, [links](https://…)) or pass blocks JSON. Returns the file link.",
  kind: "spend",
  minRole: "editor",
  argsSchema: {
    type: "object",
    properties: {
      title: { type: "string", description: "Document title (also the file name)." },
      markdown: { type: "string", description: "The document body as markdown (use this or blocks)." },
      blocks: {
        type: "string",
        description: 'Optional JSON blocks instead of markdown: [{"type":"heading","level":1,"text":"…"},{"type":"paragraph","text":"…"},{"type":"bullet","text":"…"},{"type":"table","rows":[["A","B"],["1","2"]]}].',
      },
    },
    required: ["title"],
  },
  async execute(ctx, args) {
    if (!roleAtLeast(ctx.role, "editor")) throw new Error("editor role required");
    const title = str(args.title);
    if (!title) throw new Error("title is required");
    let blocks: DocBlock[];
    try {
      const raw = args.blocks;
      blocks =
        raw !== undefined && raw !== ""
          ? coerceDocBlocks(typeof raw === "string" ? JSON.parse(raw) : raw)
          : markdownToDocBlocks(typeof args.markdown === "string" ? args.markdown : "");
    } catch (err) {
      return { summary: `Bad document content: ${err instanceof Error ? err.message : "invalid"}`, details: { error: "bad_content" } };
    }
    if (!blocks.length) return { summary: "The document has no content — pass markdown or blocks.", details: { error: "empty" } };
    const bytes = await buildDocx({ title, blocks });
    try {
      const stored = await storeDocumentFile({ workspaceId: ctx.workspaceId, projectId: ctx.projectId, userId: ctx.userId, bytes, title, ext: "docx", mimeType: DOCX_MIME });
      return {
        summary: `Word document "${title}" saved to ${stored.file.logicalPath} (${blocks.length} blocks, ${Math.ceil(bytes.length / 1024)} KB). File ${stored.file.id}.`,
        details: { fileId: stored.file.id, url: stored.url, logicalPath: stored.file.logicalPath, blocks: blocks.length, bytes: bytes.length },
      };
    } catch (err) {
      return fsFailure(err);
    }
  },
};

export const create_spreadsheet: ToolDef = {
  name: "create_spreadsheet",
  description:
    "Create an Excel spreadsheet (.xlsx) and save it to the workspace files. Pass rows (first row = header), several sheets, or CSV text. Numbers stay numbers; text that looks like a formula is stored as text. Returns the file link.",
  kind: "spend",
  minRole: "editor",
  argsSchema: {
    type: "object",
    properties: {
      title: { type: "string", description: "Spreadsheet title (also the file name)." },
      rows: { type: "string", description: 'JSON rows for one sheet, header first: [["Month","Revenue"],["Jan",1200]].' },
      sheets: { type: "string", description: 'JSON sheets: [{"name":"Q1","rows":[["Month","Revenue"],["Jan",1200]]}, …].' },
      csv: { type: "string", description: "CSV text for one sheet (numbers are detected)." },
      sheetName: { type: "string", description: "Sheet name when passing rows or csv (default Sheet1)." },
    },
    required: ["title"],
  },
  async execute(ctx, args) {
    if (!roleAtLeast(ctx.role, "editor")) throw new Error("editor role required");
    const title = str(args.title);
    if (!title) throw new Error("title is required");
    let sheets: SheetInput[];
    let bytes: Buffer;
    try {
      sheets = parseSheetArgs(args);
      bytes = await buildXlsx({ title, sheets });
    } catch (err) {
      return { summary: `Bad spreadsheet content: ${err instanceof Error ? err.message : "invalid"}`, details: { error: "bad_content" } };
    }
    try {
      const stored = await storeDocumentFile({ workspaceId: ctx.workspaceId, projectId: ctx.projectId, userId: ctx.userId, bytes, title, ext: "xlsx", mimeType: XLSX_MIME });
      const rows = sheets.reduce((n, s) => n + s.rows.length, 0);
      return {
        summary: `Spreadsheet "${title}" saved to ${stored.file.logicalPath} (${sheets.length} sheet${sheets.length === 1 ? "" : "s"}, ${rows} rows). File ${stored.file.id}.`,
        details: { fileId: stored.file.id, url: stored.url, logicalPath: stored.file.logicalPath, sheets: sheets.map((s) => ({ name: s.name, rows: s.rows.length })) },
      };
    } catch (err) {
      return fsFailure(err);
    }
  },
};

export const DOCUMENT_TOOLS: readonly ToolDef[] = [create_document, create_spreadsheet];

let registered = false;
export function registerDocumentTools(): void {
  if (registered) return;
  registered = true;
  for (const t of DOCUMENT_TOOLS) registerExtraTool(t);
}

registerDocumentTools();
