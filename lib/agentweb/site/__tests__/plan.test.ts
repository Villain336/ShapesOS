// Phase 21A (WS=agentweb): the agent-ready plan, end to end on a fixture site
// (pure: files in, files + before/after readiness out; the draft saver is a thin
// wrapper over it).
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { planAgentReady, readinessInputFromFiles } from "../plan";
import { parseLlmsTxt } from "../llmstxt";
import { policyOf } from "../robots-ai";
import { extractJsonLdBlocks } from "@/lib/audit/structured-data";

const ORIGIN = "https://riverside.test";
const SITE = [
  {
    path: "/index.html",
    content: `<!doctype html><html lang="en"><head><title>Riverside Dental</title><meta name="description" content="A family dental practice in Riverside."></head><body><h1>Riverside Dental</h1><p>A family practice. Call <a href="tel:01234567890">01234 567890</a>.</p></body></html>`,
  },
  {
    path: "/contact.html",
    content: `<!doctype html><html lang="en"><head><title>Contact</title></head><body><h1>Contact</h1><form action="/contact" method="post"><label for="e">Email</label><input id="e" name="email" type="email"><label for="m">Message</label><textarea id="m" name="message"></textarea><button>Send</button></form></body></html>`,
  },
  {
    path: "/book.html",
    content: `<!doctype html><html lang="en"><head><title>Book</title></head><body><h1>Book</h1><form action="/book" method="post"><label for="d">Date</label><input id="d" name="date" type="date"><button>Book an appointment</button></form></body></html>`,
  },
  { path: "/draft.html", content: `<meta name="robots" content="noindex"><h1>Draft</h1><p>Secret draft.</p>` },
];
const POLICY = { search: true, input: true, train: false };
const run = (files = SITE, policy = POLICY) => planAgentReady({ files, origin: ORIGIN, siteName: "Riverside Dental", policy });
const read = (files: { path: string; content: string }[], path: string) => files.find((f) => f.path === path)?.content;

describe("planAgentReady", () => {
  const plan = run();

  it("annotates the forms as WebMCP tools, never auto-submit", () => {
    assert.match(read(plan.files, "/contact.html")!, /toolname="contact_us"/);
    assert.match(read(plan.files, "/book.html")!, /toolname="request_booking"/);
    assert.ok(!plan.files.some((f) => /toolautosubmit/i.test(f.content)));
  });

  it("puts contact and booking actions plus the phone number on the Organization block", () => {
    const blocks = extractJsonLdBlocks(read(plan.files, "/index.html")!).map((b) => JSON.parse(b.raw));
    const org = blocks.find((b) => b["@type"] === "Organization");
    assert.equal(org.telephone, "01234567890");
    assert.deepEqual(
      org.potentialAction.map((a: { "@type": string; target: { urlTemplate: string } }) => [a["@type"], a.target.urlTemplate]),
      [
        ["CommunicateAction", "https://riverside.test/contact"],
        ["ReserveAction", "https://riverside.test/book"],
      ],
    );
  });

  it("writes an llms.txt that parses, lists indexable pages only and carries the ownership marker", () => {
    const llms = read(plan.files, "/llms.txt")!;
    const parsed = parseLlmsTxt(llms);
    assert.ok(parsed.valid, parsed.problems.join(";"));
    assert.equal(parsed.title, "Riverside Dental");
    assert.equal(parsed.summary, "A family dental practice in Riverside.");
    assert.ok(llms.includes("https://riverside.test/contact"));
    assert.ok(!llms.includes("draft"));
    assert.match(llms, /Generated by ShapesOS/);
  });

  it("writes robots.txt with the chosen AI policy and the sitemap line", () => {
    const robots = read(plan.files, "/robots.txt")!;
    assert.deepEqual(policyOf(robots), POLICY);
    assert.match(robots, /^Sitemap: https:\/\/riverside\.test\/sitemap\.xml$/m);
    assert.match(robots, /User-agent: GPTBot[\s\S]*Disallow: \//);
  });

  it("improves the readiness score and says what changed", () => {
    assert.ok(plan.before.score < 25, `before ${plan.before.score}`);
    assert.ok(plan.after.score >= 90, `after ${plan.after.score}`);
    assert.deepEqual(plan.changes.map((c) => c.path).sort(), ["/book.html", "/contact.html", "/index.html", "/llms.txt", "/robots.txt"]);
  });

  it("is idempotent: planning its own output changes nothing", () => {
    const again = run(plan.files);
    assert.deepEqual(again.files, plan.files);
    assert.deepEqual(again.changes, []);
  });

  it("keeps an llms.txt and robots rules the owner wrote", () => {
    const own = [...SITE, { path: "/llms.txt", content: "# Mine\n\n> Hand written.\n\n## Pages\n\n- [Home](https://riverside.test/)\n" }, { path: "/robots.txt", content: "User-agent: *\nDisallow: /private/\n" }];
    const p = run(own);
    assert.equal(read(p.files, "/llms.txt"), own[4].content);
    assert.deepEqual(p.kept.map((k) => k.path), ["/llms.txt"]);
    assert.match(read(p.files, "/robots.txt")!, /Disallow: \/private\//);
  });

  it("changing the policy changes only the AI section", () => {
    const strict = run(plan.files, { search: false, input: false, train: false });
    assert.deepEqual(policyOf(read(strict.files, "/robots.txt") ?? null), { search: false, input: false, train: false });
    assert.deepEqual(strict.changes.map((c) => c.path), ["/robots.txt"]);
  });

  it("a site without forms or contact details gets the files but no invented actions", () => {
    const p = run([{ path: "/index.html", content: "<html><head><title>x</title></head><body><h1>Hello</h1><p>Plain.</p></body></html>" }]);
    assert.ok(!/potentialAction/.test(read(p.files, "/index.html")!));
    assert.ok(read(p.files, "/llms.txt"));
  });
});

describe("readinessInputFromFiles", () => {
  it("reads pages and well-known files from a working copy, static hosting", () => {
    const i = readinessInputFromFiles([...SITE, { path: "/robots.txt", content: "x" }, { path: "/style.css", content: "a{}" }], ORIGIN);
    assert.equal(i.endpoints, false);
    assert.equal(i.pages.length, 4);
    assert.deepEqual(i.files["/robots.txt"], { status: 200, body: "x" });
    assert.equal(i.files["/llms.txt"], undefined);
  });
});
