// ShapesOS — Phase 21A (WS=agentweb): the agent-ready plan for a SiteBuilder site
// (PURE: files in, files out). lib/agentweb/site/agent-ready-draft.ts reads the
// working copy, calls this, and saves the result as a DRAFT revision; nothing here
// touches a database or the network.
//
// What it writes, and what it never overwrites:
//   - contact / booking / quote forms get WebMCP annotations (never toolautosubmit);
//   - the home page's ShapesOS-owned Organization JSON-LD gains potentialAction and
//     the phone/email the site already publishes (hand-written JSON-LD is left alone);
//   - /llms.txt is written only if absent or already ours (marker line);
//   - /robots.txt gets the tenant's AI-usage section and a Sitemap line; the owner's
//     own rules stay as they are.
// A static site cannot run /ask or /mcp, so those are not promised here (the
// storefront, which ShapesOS serves, has them).

import { injectJsonLd, injectedJsonLd, generateJsonLd, suggestJsonLdForPage, urlPathForFile, validateJsonLd, type JsonLd } from "@/lib/seo/jsonld";
import type { SiteFile } from "@/lib/sites/files";
import { attr, findAll, parseHtml } from "../html";
import { addPotentialActions, annotateForms, contactDetails, findForms, potentialActions, type SiteTask, type SiteTaskKind } from "./actions";
import { buildLlmsTxt, type LlmsLink } from "./llmstxt";
import { docsFromHtml } from "./corpus";
import { assessReadiness, type ReadinessInput, type ReadinessReport } from "./readiness";
import { applyAiPolicy, type AiPolicy } from "./robots-ai";

export const LLMS_MARKER = "<!-- Generated by ShapesOS Agent readiness: rebuilt when you re-run it. Remove this line to manage the file by hand. -->";

export interface AgentReadyInput {
  files: SiteFile[];
  origin: string;
  siteName: string;
  logo?: string | null;
  sameAs?: string[];
  policy: AiPolicy;
}
export interface PlanChange {
  path: string;
  what: string;
}
export interface AgentReadyPlan {
  files: SiteFile[];
  changes: PlanChange[];
  kept: { path: string; reason: string }[];
  before: ReadinessReport;
  after: ReadinessReport;
}

const HTML = /\.html?$/i;
const TASK_TITLE: Record<SiteTaskKind, string> = { contact: "Contact us", booking: "Book an appointment", quote: "Ask for a quote" };

export function readinessInputFromFiles(files: SiteFile[], origin: string): ReadinessInput {
  const wellKnown: ReadinessInput["files"] = {};
  for (const path of ["/llms.txt", "/robots.txt", "/sitemap.xml"]) {
    const f = files.find((x) => x.path === path);
    if (f) wellKnown[path] = { status: 200, body: f.content };
  }
  return { origin, pages: files.filter((f) => HTML.test(f.path)).map((f) => ({ path: f.path, html: f.content })), files: wellKnown, endpoints: false };
}

const metaDescription = (html: string): string | null => {
  const m = findAll(parseHtml(html), (n) => n.tag === "meta" && (attr(n, "name") ?? "").toLowerCase() === "description")[0];
  const v = m ? attr(m, "content")?.replace(/\s+/g, " ").trim() : "";
  return v || null;
};

export function planAgentReady(input: AgentReadyInput): AgentReadyPlan {
  const origin = input.origin.replace(/\/+$/, "");
  const before = assessReadiness(readinessInputFromFiles(input.files, origin));
  const out = new Map(input.files.map((f) => [f.path, f.content]));
  const changes: PlanChange[] = [];
  const kept: AgentReadyPlan["kept"] = [];
  const set = (path: string, content: string, what: string) => {
    if (out.get(path) === content) return;
    out.set(path, content);
    changes.push({ path, what });
  };
  const pagePaths = input.files.filter((f) => HTML.test(f.path)).map((f) => f.path);

  // 1. WebMCP annotations on the task forms.
  for (const path of pagePaths) {
    const r = annotateForms(out.get(path)!, { siteName: input.siteName });
    if (r.annotated) set(path, r.html, `${r.annotated} form${r.annotated === 1 ? "" : "s"} annotated as WebMCP tool${r.annotated === 1 ? "" : "s"}`);
  }

  // 2. The tasks the site really has, with absolute submit targets.
  const tasks: SiteTask[] = [];
  const taskPages: { kind: SiteTaskKind; url: string }[] = [];
  for (const path of pagePaths) {
    const pageUrl = `${origin}${urlPathForFile(path)}`;
    for (const f of findForms(out.get(path)!)) {
      if (!f.kind || /^\s*(#|javascript:)/i.test(f.action)) continue;
      try {
        tasks.push({ kind: f.kind, target: new URL(f.action || pageUrl, pageUrl).toString(), method: f.method });
        taskPages.push({ kind: f.kind, url: pageUrl });
      } catch {
        /* an action that is not a URL is not a task */
      }
    }
  }

  // 3. Organization JSON-LD on the home page: actions + the contact details already published.
  const homePath = pagePaths.find((p) => /^\/?index\.html?$/i.test(p)) ?? pagePaths[0];
  const contact = contactDetails(pagePaths.map((p) => ({ path: p, html: out.get(p)! })));
  if (homePath && (tasks.length || contact.email || contact.telephone)) {
    const html = out.get(homePath)!;
    const identity = { name: input.siteName, origin, logo: input.logo ?? null, sameAs: input.sameAs };
    const fresh = suggestJsonLdForPage(homePath, html, identity).map((b) => (b["@type"] === "Organization" ? enrichOrganization(input, origin, contact, tasks) : b));
    const types = new Set(fresh.map((b) => JSON.stringify(b["@type"])));
    const keep = injectedJsonLd(html).filter((b) => !types.has(JSON.stringify(b["@type"])));
    const blocks = [...fresh, ...keep];
    if (blocks.every((b) => !validateJsonLd(b).some((i) => i.severity === "error"))) {
      set(homePath, injectJsonLd(html, blocks), `schema.org Organization with ${tasks.length} action${tasks.length === 1 ? "" : "s"}${contact.telephone || contact.email ? " and contact details" : ""}`);
    } else {
      kept.push({ path: homePath, reason: "the generated structured data did not validate, so nothing was written" });
    }
  }

  // 4. llms.txt: ours is rebuilt, the owner's is kept.
  const existingLlms = out.get("/llms.txt");
  if (existingLlms !== undefined && !existingLlms.includes("Generated by ShapesOS")) {
    kept.push({ path: "/llms.txt", reason: "you wrote this file, so it was left as it is" });
  } else {
    const docs = docsFromHtml(pagePaths.map((p) => ({ path: p, html: out.get(p)! })), origin);
    const notes = new Map(pagePaths.map((p) => [`${origin}${urlPathForFile(p)}`, metaDescription(out.get(p)!)]));
    const links: LlmsLink[] = docs.map((d) => ({ title: d.name, url: d.url, ...(notes.get(d.url) ? { notes: notes.get(d.url)!.slice(0, 140) } : {}) }));
    const homeDoc = docs.find((d) => d.url === `${origin}/`) ?? docs[0];
    const summary = (homePath && metaDescription(out.get(homePath)!)) || (homeDoc ? homeDoc.text.split(/(?<=[.!?])\s/)[0] : "") || input.siteName;
    const seen = new Set<string>();
    const taskLinks: LlmsLink[] = taskPages.filter((t) => !seen.has(`${t.kind}|${t.url}`) && seen.add(`${t.kind}|${t.url}`)).map((t) => ({ title: TASK_TITLE[t.kind], url: t.url }));
    const text = `${buildLlmsTxt({ name: input.siteName, summary, sections: [{ title: "Pages", links }, { title: "Things you can do", links: taskLinks }] }).trimEnd()}\n\n${LLMS_MARKER}\n`;
    set("/llms.txt", text, existingLlms === undefined ? "new llms.txt" : "llms.txt rebuilt");
  }

  // 5. robots.txt: the tenant's AI-usage section; their own rules stay.
  set("/robots.txt", applyAiPolicy(out.get("/robots.txt") ?? null, input.policy, { sitemapUrl: `${origin}/sitemap.xml` }), out.has("/robots.txt") ? "AI-usage section updated" : "new robots.txt with an AI-usage section");

  const files = [...input.files.map((f) => ({ path: f.path, content: out.get(f.path)! })), ...[...out].filter(([p]) => !input.files.some((f) => f.path === p)).map(([path, content]) => ({ path, content }))];
  const after = assessReadiness(readinessInputFromFiles(files, origin));
  return { files, changes, kept, before, after };
}

function enrichOrganization(input: AgentReadyInput, origin: string, contact: { email?: string; telephone?: string }, tasks: SiteTask[]): JsonLd {
  const org = generateJsonLd("Organization", { name: input.siteName, url: `${origin}/`, logo: input.logo ?? undefined, sameAs: input.sameAs, email: contact.email, telephone: contact.telephone });
  const withContact: JsonLd =
    contact.email || contact.telephone
      ? { ...org, contactPoint: { "@type": "ContactPoint", contactType: "customer service", ...(contact.email ? { email: contact.email } : {}), ...(contact.telephone ? { telephone: contact.telephone } : {}) } }
      : org;
  return addPotentialActions(withContact, potentialActions(tasks, input.siteName));
}
