// Marketr — scheduler run executor (Phase B, W2).
// (Threat models T4: subagent privilege escalation, T7: concurrency-cap bypass.)
//
// Phase 8: with a live model each subtask runs on the real agent loop
// (lib/scheduler/live.ts — an AgentRun per subtask, the skill's declared
// tools as its allow-list); in mock mode (no live LLM) the deterministic mock
// subagent below stands in, clearly labelled. The executor is real in every
// other respect: grant envelopes are enforced, subagent runs are separate DB
// rows, each is separately audited and credit-metered, fan-out respects the
// concurrency cap, and outputs go through the output store at
// /artifacts/runs/<run-id>/.

import type { PrismaClient, Skill } from "@prisma/client";
import { createHash } from "node:crypto";
import {
  SUBAGENT_SPAWN_CREDITS,
  SKILL_RUN_BASE_CREDITS,
  MOCK_ACTION_CREDITS,
} from "./credits";
import { effectiveConcurrency, DEFAULT_CONCURRENCY } from "./guard";
import { getOutputStoreAsync, type SchedulerOutputStore } from "./outputStore";
import { schedulerAudit } from "./audit";
import { checkCap, meter } from "@/lib/metering/service";

export interface GrantEnvelope {
  workspaceId: string;
  projectId: string | null;
  skillId: string;
  skillName: string;
  /** Tools the skill declared at install time — the subagent may use only these. */
  declaredTools: string[];
  parentRunId: string;
  scheduleId: string | null;
}

export interface Subtask {
  label: string;
  /** Tool the mock subtask "calls". Null = pure analysis, no tool. */
  tool: string | null;
  detail: string;
}

export interface ExecutorDeps {
  outputStore?: SchedulerOutputStore;
  /** Override decomposition (used by the adversarial battery). */
  subtasks?: Subtask[];
  /** Workspace-level default concurrency (admin-configurable; default 4). */
  workspaceConcurrency?: number;
  /**
   * Phase 8: run a subtask on the real agent loop. Default: the live runner
   * when a model is live for the agent workloads, else null (mock subagents).
   */
  runSubtask?: import("./live").LiveSubtaskRunner | null;
}

/** True when the tool is inside the parent run's grant envelope. */
export function isToolAllowed(envelope: GrantEnvelope, tool: string | null): boolean {
  if (!tool) return true; // pure analysis, no tool call
  return envelope.declaredTools.includes(tool);
}

/** Deterministic subtask decomposition from a skill (mock of the real planner). */
export function decomposeSkill(skill: Skill): Subtask[] {
  const templates: Record<string, string[]> = {
    "seo-audit": ["crawl summary", "issue triage", "recommendations"],
    "rank-tracker": ["fetch rankings", "detect movers", "summarize"],
    "content-brief": ["research topic", "outline brief", "write brief"],
  };
  const key = skill.slug in templates ? skill.slug : "default";
  const labels =
    templates[key] ?? ["gather context", "analyze", "draft findings", "assemble report"];
  return labels.map((label, i) => ({
    label,
    tool: skill.declaredTools.length > 0 ? skill.declaredTools[i % skill.declaredTools.length] : null,
    detail: `Subtask ${i + 1} of ${labels.length} for skill "${skill.name}".`,
  }));
}

/** Deterministic mock subagent result — no LLM, no network. */
export function mockSubagentResult(taskLabel: string, skillName: string, tool: string | null): string {
  const digest = createHash("sha256").update(`${skillName}:${taskLabel}:${tool ?? "none"}`).digest("hex").slice(0, 8);
  return [
    `# ${taskLabel}`,
    ``,
    `Skill: ${skillName}${tool ? ` · tool: ${tool}` : ""}`,
    `Run digest: ${digest}`,
    ``,
    `Findings (mock executor — replace with live agent loop in Phase C LLM work):`,
    `- Checked the declared inputs for "${taskLabel}".`,
    `- No external calls were made; this output is deterministic for testing.`,
    `- Digest ${digest} pins this result to the task inputs above.`,
  ].join("\n");
}

function buildReport(params: {
  skillName: string;
  trigger: string;
  subagentResults: { label: string; tool: string | null; status: string; credits: number; result: string | null }[];
  creditsUsed: number;
  eventDescription?: string | null;
  live?: boolean;
}): string {
  const lines = [
    `# Skill run report — ${params.skillName}`,
    ``,
    `- Trigger: ${params.trigger}`,
    ...(params.eventDescription ? [`- Firing event: ${params.eventDescription}`] : []),
    `- Subagents: ${params.subagentResults.length}`,
    `- Credits used: ${params.creditsUsed}`,
    ``,
    `## Subagent breakdown`,
    ``,
  ];
  for (const r of params.subagentResults) {
    lines.push(`### ${r.label} — ${r.status} (${r.credits} credits)`);
    lines.push(r.tool ? `Tool: ${r.tool}` : `Tool: none (analysis only)`);
    lines.push("");
    lines.push(r.result ?? "_no result_");
    lines.push("");
  }
  lines.push(
    params.live
      ? `_Generated by the ShapesOS scheduler on the live agent loop (one agent run per subtask)._`
      : `_Generated by the ShapesOS scheduler mock executor (no live LLM is configured, so no model was called)._`,
  );
  return lines.join("\n");
}

/** Counting semaphore fan-out: at most `limit` subtasks in flight. */
export async function runWithLimit<T, R>(
  items: T[],
  limit: number,
  fn: (item: T, index: number) => Promise<R>,
): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  const worker = async () => {
    while (true) {
      const i = next++;
      if (i >= items.length) return;
      results[i] = await fn(items[i], i);
    }
  };
  const workers = Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, () => worker());
  await Promise.all(workers);
  return results;
}

type Db = PrismaClient;

/**
 * Phase C (W4): record a scheduler charge against the metering ledger.
 *
 * Metering never fails a run: a blocked charge (spend cap) or a ledger
 * error is audit-logged loudly and the run continues — the run row's own
 * creditsUsed field remains the local record. Idempotency keys are derived
 * from the run/subagent row IDs, so retried executions never double-charge.
 */
async function recordMeterCharge(
  db: Db,
  args: {
    workspaceId: string;
    projectId: string | null;
    action: "skill_run_base" | "subagent_spawn";
    credits: number;
    idempotencyKey: string;
    evidenceRef: string;
    label: string;
  },
): Promise<void> {
  try {
    const res = await meter({
      workspaceId: args.workspaceId,
      projectId: args.projectId,
      action: args.action,
      credits: args.credits,
      idempotencyKey: args.idempotencyKey,
      evidenceRef: args.evidenceRef,
    });
    if (!res.ok) {
      await schedulerAudit(db, {
        projectId: args.projectId,
        workspaceId: args.workspaceId,
        action: "scheduler_metering_blocked",
        summary: `Metering blocked for ${args.label}: ${res.message}`,
        actorUserId: null,
      });
    }
  } catch (err) {
    await schedulerAudit(db, {
      projectId: args.projectId,
      workspaceId: args.workspaceId,
      action: "scheduler_metering_failed",
      summary: `Metering failed for ${args.label}: ${err instanceof Error ? err.message : String(err)}`.slice(0, 500),
      actorUserId: null,
    });
  }
}

/**
 * Execute a skill run: fan out subtasks to subagents under the concurrency cap,
 * enforce the grant envelope, aggregate into one report, write the output,
 * and record credits. Called for scheduled/autopilot runs and for approved
 * supervised runs. Never called for runs still awaiting approval.
 */
export async function executeSkillRun(db: Db, runId: string, deps: ExecutorDeps = {}): Promise<void> {
  const store = deps.outputStore ?? (await getOutputStoreAsync());
  const run = await db.skillRun.findUnique({
    where: { id: runId },
    include: { skill: true, schedule: true },
  });
  if (!run) throw new Error(`skill run not found: ${runId}`);
  if (run.status !== "pending" && run.status !== "approved") {
    throw new Error(`cannot execute skill run in status ${run.status}`);
  }

  // Phase C gaps (G1) — pre-run cap gate (T9): never start work the workspace
  // can't pay for. Advisory only; meter() stays the authoritative per-charge
  // check (the post-run charges below still reconcile, and cannot double
  // charge — the gate never writes to the ledger).
  const gate = await checkCap(run.workspaceId);
  if (!gate.allowed) {
    const reason =
      `Credit cap reached (${gate.used.toLocaleString()} of ${gate.capCredits.toLocaleString()} ` +
      `credits used). Raise the cap or add credits in Settings → Usage.`;
    await db.skillRun.update({
      where: { id: run.id },
      data: { status: "blocked", finishedAt: new Date(), error: reason },
    });
    await schedulerAudit(db, {
      projectId: run.projectId,
      workspaceId: run.workspaceId,
      action: "scheduler_run_blocked_cap",
      summary: `Skill run blocked before execution: ${reason}`,
      actorUserId: null,
    });
    return;
  }

  const skill = run.skill;
  const schedule = run.schedule;
  const envelope: GrantEnvelope = {
    workspaceId: run.workspaceId,
    projectId: run.projectId,
    skillId: run.skillId,
    skillName: skill.name,
    declaredTools: skill.declaredTools ?? [],
    parentRunId: run.id,
    scheduleId: run.scheduleId,
  };

  await db.skillRun.update({ where: { id: run.id }, data: { status: "running", startedAt: new Date() } });
  await schedulerAudit(db, {
    projectId: run.projectId,
    workspaceId: run.workspaceId,
    action: "scheduler_run_started",
    summary: `Skill run started: "${skill.name}" (trigger ${run.trigger})`,
    actorUserId: null,
  });

  // Phase 16: the AgentRun the live subtasks hang under (one tree, one Stop).
  let parentAgentRunId: string | null = null;
  try {
    const subtasks = deps.subtasks ?? decomposeSkill(skill);
    // Phase 8: the real agent loop when a model is live; mock otherwise.
    let runLive: import("./live").LiveSubtaskRunner | null = null;
    if (deps.runSubtask !== undefined) runLive = deps.runSubtask;
    else {
      const live = await import("./live");
      runLive = live.schedulerLoopIsLive() ? live.runSkillSubtaskLive : null;
    }

    // T7: per-run semaphore + cross-run guard (active subagents of sibling
    // runs under the same schedule also count against the cap).
    const cap = effectiveConcurrency(schedule?.concurrencyLimit ?? DEFAULT_CONCURRENCY, deps.workspaceConcurrency ?? DEFAULT_CONCURRENCY);
    let activeElsewhere = 0;
    if (run.scheduleId) {
      activeElsewhere = await db.subagentRun.count({
        where: {
          status: "running",
          skillRun: { scheduleId: run.scheduleId, id: { not: run.id }, status: "running" },
        },
      });
    }
    const limit = Math.max(1, cap - activeElsewhere);

    // Phase 16: live subtasks hang under one AgentRun for this skill run.
    parentAgentRunId = runLive
      ? await (await import("./live")).createSkillParentRun({ workspaceId: run.workspaceId, skillRunId: run.id, skillName: skill.name, projectId: run.projectId })
      : null;

    const subagentResults = await runWithLimit(subtasks, limit, async (subtask) => {
      const sub = await db.subagentRun.create({
        data: { skillRunId: run.id, taskLabel: subtask.label, status: "pending" },
      });
      await db.subagentRun.update({ where: { id: sub.id }, data: { status: "running" } });
      await schedulerAudit(db, {
        projectId: run.projectId,
        workspaceId: run.workspaceId,
        action: "subagent_run_started",
        summary: `Subagent started: "${subtask.label}" (run ${run.id.slice(0, 8)})`,
        actorUserId: null,
      });

      // T4: the grant envelope is enforced per subagent, per tool call.
      if (!isToolAllowed(envelope, subtask.tool)) {
        await db.subagentRun.update({
          where: { id: sub.id },
          data: { status: "skipped", finishedAt: new Date(), creditsUsed: 0 },
        });
        await schedulerAudit(db, {
          projectId: run.projectId,
          workspaceId: run.workspaceId,
          action: "connector_tool_denied",
          summary: `Subagent "${subtask.label}" denied tool "${subtask.tool}" — outside the parent run's grant envelope`,
          actorUserId: null,
        });
        return { label: subtask.label, tool: subtask.tool, status: "skipped", credits: 0, result: null };
      }

      let result: string;
      let subStatus: "succeeded" | "failed" = "succeeded";
      if (runLive) {
        try {
          const live = await runLive({
            workspaceId: run.workspaceId,
            projectId: run.projectId,
            skill,
            subtask,
            skillRunId: run.id,
            subagentRunId: sub.id,
            ...(parentAgentRunId ? { parentRunId: parentAgentRunId } : {}),
          });
          result = `${live.result}\n\nAgent run: ${live.runId}`;
          subStatus = live.status;
        } catch (err) {
          result = `Subagent failed: ${err instanceof Error ? err.message : String(err)}`;
          subStatus = "failed";
        }
      } else {
        result = mockSubagentResult(subtask.label, skill.name, subtask.tool);
      }
      const credits = SUBAGENT_SPAWN_CREDITS + MOCK_ACTION_CREDITS.subtask_analysis;
      await db.subagentRun.update({
        where: { id: sub.id },
        data: { status: subStatus, finishedAt: new Date(), creditsUsed: credits, result },
      });
      // Phase C (W4): ledger the spawn fee + this subagent's actions.
      await recordMeterCharge(db, {
        workspaceId: run.workspaceId,
        projectId: run.projectId,
        action: "subagent_spawn",
        credits,
        idempotencyKey: `subagent-run:${sub.id}`,
        evidenceRef: `subagent-run:${sub.id}`,
        label: `subagent "${subtask.label}"`,
      });
      await schedulerAudit(db, {
        projectId: run.projectId,
        workspaceId: run.workspaceId,
        action: "subagent_run_finished",
        summary: `Subagent finished: "${subtask.label}" (${credits} credits)`,
        actorUserId: null,
      });
      return { label: subtask.label, tool: subtask.tool, status: subStatus, credits, result };
    });

    if (parentAgentRunId) {
      const { finishAgentRun, isAgentRunCancelRequested } = await import("@/lib/agents/runs/service");
      const stopped = await isAgentRunCancelRequested(run.workspaceId, parentAgentRunId).catch(() => false);
      await finishAgentRun(
        run.workspaceId,
        parentAgentRunId,
        stopped ? "cancelled" : subagentResults.some((r) => r.status === "failed") ? "failed" : "succeeded",
      ).catch(() => undefined);
    }

    const creditsUsed =
      SKILL_RUN_BASE_CREDITS +
      subagentResults.reduce((sum, r) => sum + r.credits, 0) +
      MOCK_ACTION_CREDITS.report_assembly;

    const report = buildReport({
      skillName: skill.name,
      trigger: run.trigger,
      subagentResults,
      creditsUsed,
      eventDescription: null,
      live: runLive !== null,
    });
    const { logicalPath } = await store.writeReport(run.workspaceId, run.id, "report.md", report);

    await db.skillRun.update({
      where: { id: run.id },
      data: {
        status: "succeeded",
        finishedAt: new Date(),
        creditsUsed,
        outputPath: logicalPath,
      },
    });
    await schedulerAudit(db, {
      projectId: run.projectId,
      workspaceId: run.workspaceId,
      action: "scheduler_run_finished",
      summary: `Skill run finished: "${skill.name}" — ${subagentResults.length} subagents, ${creditsUsed} credits, output ${logicalPath}`,
      actorUserId: null,
    });
    // Phase C (W4): ledger the run-level charge (base + report assembly).
    // Subagent charges were ledgered inline above; the three meter() calls
    // sum to exactly creditsUsed.
    await recordMeterCharge(db, {
      workspaceId: run.workspaceId,
      projectId: run.projectId,
      action: "skill_run_base",
      credits: SKILL_RUN_BASE_CREDITS + MOCK_ACTION_CREDITS.report_assembly,
      idempotencyKey: `skill-run:${run.id}`,
      evidenceRef: `skill-run:${run.id}`,
      label: `skill run ${run.id.slice(0, 8)}`,
    });
    if (schedule?.approvalMode === "scheduled") {
      await schedulerAudit(db, {
        projectId: run.projectId,
        workspaceId: run.workspaceId,
        action: "scheduler_run_reported",
        summary: `Run report ready for "${skill.name}" (${creditsUsed} credits)`,
        actorUserId: null,
      });
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    if (parentAgentRunId) {
      const { finishAgentRun } = await import("@/lib/agents/runs/service");
      await finishAgentRun(run.workspaceId, parentAgentRunId, "failed").catch(() => undefined);
    }
    await db.skillRun.update({
      where: { id: run.id },
      data: { status: "failed", finishedAt: new Date(), error: message.slice(0, 2000) },
    });
    await schedulerAudit(db, {
      projectId: run.projectId,
      workspaceId: run.workspaceId,
      action: "scheduler_run_failed",
      summary: `Skill run failed: "${skill.name}" — ${message.slice(0, 300)}`,
      actorUserId: null,
    });
    // Phase C (W4): a failed run still consumed the base orchestration.
    await recordMeterCharge(db, {
      workspaceId: run.workspaceId,
      projectId: run.projectId,
      action: "skill_run_base",
      credits: SKILL_RUN_BASE_CREDITS,
      idempotencyKey: `skill-run:${run.id}`,
      evidenceRef: `skill-run:${run.id}`,
      label: `failed skill run ${run.id.slice(0, 8)}`,
    });
    throw err;
  }
}
