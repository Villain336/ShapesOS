// Marketr — one-shot bake of orb-14's WGSL.
// Run: node scripts/bake-orb14-shader.mjs
//
// Why this exists: the orb-14 registry file (components/orbs/orb-14/gpu.ts)
// defines its shader with TypeGPU `"use gpu"` functions, which require the
// unplugin-typegpu build transform. Next.js 16 builds with Turbopack, where
// that bundler plugin cannot run — so importing gpu.ts in the browser throws
// "Missing metadata for tgpu.fn function body" and crashes the page.
//
// The shader itself is fully static (every runtime variation flows through
// uniforms), so we resolve it ONCE here with esbuild + unplugin-typegpu and
// bake the resulting WGSL string into components/orbs/orb-14/shader.baked.ts.
// The farm (BrainOrbFarm) uses the baked string; the registry files stay
// byte-identical to the official @shadercn/orb-14 distribution.
import { build } from "esbuild";
import typegpu from "unplugin-typegpu/esbuild";
import { writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = "/home/hatch/workspace/marketr";

const entry = `
import { orb14Shader } from ${JSON.stringify(join(ROOT, "components/orbs/orb-14/gpu.ts"))};
export const shader = orb14Shader;
`;

const dir = mkdtempSync(join(tmpdir(), "orb14-bake-"));
const outfile = join(dir, "orb14.bundle.mjs");

try {
  await build({
    stdin: {
      contents: entry,
      loader: "ts",
      resolveDir: ROOT,
    },
    bundle: true,
    platform: "node",
    format: "esm",
    outfile,
    plugins: [typegpu()],
    logLevel: "warning",
  });

  const mod = await import(pathToFileURL(outfile).href);
  const wgsl = mod.shader;
  if (typeof wgsl !== "string" || wgsl.length < 100) {
    throw new Error(`resolved WGSL looks wrong (length ${String(wgsl)?.length})`);
  }
  console.log(`resolved WGSL: ${wgsl.length} chars`);

  const outPath = join(ROOT, "components/orbs/orb-14/shader.baked.ts");
  const header = `// Marketr — baked WGSL for @shadercn/orb-14.
// Generated by scripts/bake-orb14-shader.mjs (esbuild + unplugin-typegpu).
// Source of truth: components/orbs/orb-14/gpu.ts (official registry file,
// byte-identical to https://shadercn.run/r/orb-14.json). This baked string is
// the output of tgpu.resolve([orb14Fragment]) — the shader is fully static;
// all runtime variation flows through uniforms. Re-bake after any gpu.ts change.
//
// Shader by XorDev (https://x.com/XorDev), ported for Orbkit with the author's
// permission. Non-commercial use only, with attribution to XorDev; keep this
// notice with the file. shadercn's runtime (renderer.ts) is MIT-licensed.
`;
  writeFileSync(outPath, `${header}\nexport const orb14ShaderBaked = ${JSON.stringify(wgsl)};\n`);
  console.log(`wrote ${outPath}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
